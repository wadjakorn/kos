# ---------------------------------------------------------------------------
# Paths — the *data root* ("the db") is configurable so knowledge can live in
# its own directory (and its own git history) outside this code repo.
#
# Resolution order (see init_paths / _resolve_data_root):
#   1. KOS_DATA_ROOT env var
#   2. config/paths.json -> {"data_root": "..."} (machine-local, gitignored)
#   3. sibling ../db — the standard layout: knowledge-base/{kos,db}
#      (code repo = kos/, data repo = db/, side by side).
#
# CONFIG (extractor config) is *engine* config, not knowledge — it always
# stays in the code repo, never moving with the data.
# ---------------------------------------------------------------------------
_REPO_ROOT = Path(__file__).resolve().parent.parent
CONFIG = _REPO_ROOT / "config" / "extractor.json"

# Data-root-derived paths. Populated by init_paths() (called at import below)
# and re-callable to repoint the whole engine (tests do exactly this).
ROOT = SOURCES = ATOMS = THESES = PROJECTS = INDEXES = LOGS = CACHE = None  # type: ignore[assignment]


def _resolve_data_root() -> Path:
    """Resolve the knowledge data root: env > config/paths.json > sibling ../db."""
    env = os.environ.get("KOS_DATA_ROOT")
    if env:
        return Path(env).expanduser().resolve()
    cfg = _REPO_ROOT / "config" / "paths.json"
    if cfg.exists():
        try:
            data_root = json.loads(cfg.read_text(encoding="utf-8")).get("data_root")
        except (json.JSONDecodeError, OSError):
            data_root = None
        if data_root:
            return Path(data_root).expanduser().resolve()
    return (_REPO_ROOT.parent / "db").resolve()  # knowledge-base/{kos,db}


def init_paths(base: Path | None = None) -> None:
    """(Re)point all data-root-derived globals at ``base`` (or a resolved root).

    Idempotent and safe to call repeatedly; entry points call it before any
    data operation so a configured KOS_DATA_ROOT takes effect.
    """
    global ROOT, SOURCES, ATOMS, THESES, PROJECTS, INDEXES, LOGS, CACHE
    ROOT = Path(base).expanduser().resolve() if base is not None else _resolve_data_root()
    SOURCES = ROOT / "sources"
    ATOMS = ROOT / "atoms"
    THESES = ROOT / "theses"
    PROJECTS = ROOT / "projects"
    INDEXES = ROOT / "indexes"
    LOGS = ROOT / "logs"
    CACHE = ROOT / ".cache" / "extract"


init_paths()  # resolve at import so `ingest.SOURCES` etc. are usable immediately

